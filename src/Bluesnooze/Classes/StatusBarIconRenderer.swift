    /// Builds the 18x18 template status bar icon directly in memory without mapping Assets.car or SFSymbols.
    @MainActor
    static func makeStatusBarIcon() -> NSImage? {
        let image = NSImage(size: NSSize(width: 18, height: 18))
        if let rep2x = NSBitmapImageRep(data: Data(icon2xBytes)) {
            rep2x.size = NSSize(width: 18, height: 18)
            image.addRepresentation(rep2x)
        }
        if let rep1x = NSBitmapImageRep(data: Data(icon1xBytes)) {
            rep1x.size = NSSize(width: 18, height: 18)
            image.addRepresentation(rep1x)
        }
        guard !image.representations.isEmpty else { return nil }
        image.isTemplate = true
        return image
    }
